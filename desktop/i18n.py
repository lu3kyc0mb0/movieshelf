def set_language(language):
    global _language
    _language = language if language in ("en", "ru", "kk") else "en"

def t(key, **values):
    message = TRANSLATIONS.get(_language, {}).get(key, key)
    return message.format(**values) if values else message

def film_count(count):
    if _language == "ru":
        last = count % 10
        word = "фильм" if last == 1 and count % 100 != 11 else "фильма" if 2 <= last <= 4 and not 12 <= count % 100 <= 14 else "фильмов"
        return f"{count} {word}"
    if _language == "kk":
        return f"{count} фильм"
    return f"{count} film{'s' if count != 1 else ''}"
